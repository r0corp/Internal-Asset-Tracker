# msgstr_en = terjemahan Inggris, msgstr_id = sama seperti aslinya.
MENU_LABELS = {
    "Laporan Mutasi": "Movement Report",
    "Master Data": "Master Data",
    "Kategori": "Categories",
    "Lokasi": "Locations",
    "Departemen": "Departments",
    "Hapus Cache": "Clear Cache",
    "Role Akses": "Access Roles",
    "Pengaturan Aplikasi": "Application Settings",
    "Pemisah": "Divider",
}


def build_catalog(pot_path, extra_msgids):
    catalog = polib.pofile(pot_path)
    catalog.metadata_is_fuzzy = False
    existing = {entry.msgid for entry in catalog}
    for msgid in extra_msgids:
        if msgid not in existing:
            catalog.append(polib.POEntry(msgid=msgid, msgstr=""))
    return catalog


def write_en(pot_path, out_path):
    catalog = build_catalog(pot_path, MENU_LABELS.keys())
    catalog.metadata["Language"] = "en"
    for entry in catalog:
        # Sumber string memang bahasa Inggris -> identity translation,
        # KECUALI label menu (yang msgid-nya masih bahasa Indonesia).
        if entry.msgid in MENU_LABELS:
            entry.msgstr = MENU_LABELS[entry.msgid]
        else:
            entry.msgstr = entry.msgid
    catalog.save(out_path)


def write_id(pot_path, out_path):
    catalog = build_catalog(pot_path, MENU_LABELS.keys())
    catalog.metadata["Language"] = "id"
    missing = []
    for entry in catalog:
        if entry.msgid in MENU_LABELS:
            # Label menu sudah dalam bahasa Indonesia -> identity.
            entry.msgstr = entry.msgid
        elif entry.msgid in ID_TRANSLATIONS:
            entry.msgstr = ID_TRANSLATIONS[entry.msgid]
        else:
            missing.append(entry.msgid)
            entry.msgstr = entry.msgid
    catalog.save(out_path)
    return missing


if __name__ == "__main__":
    write_en(POT_PATH, EN_PO_PATH)
    missing = write_id(POT_PATH, ID_PO_PATH)

    print(f"EN catalog written: {EN_PO_PATH}")
    print(f"ID catalog written: {ID_PO_PATH}")

    if missing:
        print(f"\nWARNING: {len(missing)} msgid belum ada terjemahan ID (pakai fallback = msgid asli):")
        for m in missing:
            print(" -", repr(m))
    else:
        print("\nSemua msgid punya terjemahan ID.")
